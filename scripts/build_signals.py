# ----------------------------------------------------------------- requirements
def build_requirements(reqs):
    meta = (reqs or {}).get("meta", {})
    counts = {}
    for r in (reqs or {}).get("requirements", []):
        counts[r["status"]] = counts.get(r["status"], 0) + 1
    rows = [[esc(r["id"]), esc(r.get("area", "")), esc(r["requirement"]), st(r["status"]),
             esc(r.get("howItIsSatisfied", "")),
             "<br>".join(f"<code>{esc(e)}</code>" for e in r.get("evidence", [])),
             esc(r.get("limits", "&mdash;"))] for r in (reqs or {}).get("requirements", [])]
    body = [
        f'<p class="small">Status vocabulary — ' + " · ".join(
            f"<strong>{esc(k)}</strong> {esc(v)}" for k, v in meta.get("statusVocabulary", {}).items())
        + "</p>",
        "<p>Counts: " + ", ".join(f"{esc(k)} {v}" for k, v in sorted(counts.items()))
        + ". Every status is earned by an artefact in the repository, and the evidence column names it.</p>",
        table(["ID", "Area", "Requirement", "Status", "How it is satisfied in this build",
               "Evidence", "What it still cannot do"], rows),
        callout("flag", "Two gaps decide what can never be claimed here.",
                "There is no market-price archive, so no edge, ROI or closing-line statement is possible "
                "(R11/R12/R20); and there is no dated availability archive, so the injury adjustment cannot be "
                "judged historically (R9). Both are written as gates that fail, not as prose caveats."),
    ]
    page("nfl-signals-requirements.html", "Requirement ledger — what was asked and what exists",
         "Every requirement this build was asked to satisfy, its real status, and the file that proves it.",
         body)


