"""Render the NFL Signals Lab from its JSON artefacts.

Reads:
  data/nfl-signals/signals.json, forward-ledger.json, requirements.json, suggestions.json
  official/lab/fetch-report.json, source-registry.json, injuries-2026.json
Writes (root pages, so the existing GitHub Pages build serves them):
  nfl-signals.html                hub: verdict, scoreboard, leaderboard, gates, next steps
  nfl-signals-requirements.html  what was asked, what was built, what is still missing
  nfl-signals-data.html          the official-source capture pipeline and its integrity counters
  nfl-signals-injuries.html      availability model: weights, per-club deficits, what it cannot do
  nfl-signals-backtest.html      walk-forward leaderboard, luck, sensitivity, dependence
  nfl-signals-lines.html         model lines for upcoming games, with the hold mechanics shown
  nfl-signals-suggestions.html   review board: every suggestion raised, and its decision

The builder invents nothing: every figure comes from a JSON file a script produced from official
nfl.com captures, and the styling vocabulary is the one assets/style.css already defines. Where a
number cannot be computed, the page prints what is missing and what would unblock it, because a
blank with a reason is more useful than a plausible estimate.
"""
