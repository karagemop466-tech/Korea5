def load(rel: str, default=None):
    path = os.path.join(ROOT, rel)
    if not os.path.exists(path):
        return default
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def pct(v, digits=1):
    return "&mdash;" if v is None else f"{v * 100:.{digits}f}%"


def num(v, digits=4):
    if v is None:
        return "&mdash;"
    return f"{v:.{digits}f}" if isinstance(v, float) else esc(v)


def src(url, label: str = "official source") -> str:
    """A link to the official page, or an explicit dash: a row without a source must look like one."""
    return build_site.src(url or "", label) if url else '<span class="small">&mdash;</span>'


def st(value) -> str:
    if value is None:
        return "&mdash;"
    return f'<span class="{STATUS_CLASS.get(str(value), "tag")}">{esc(value)}</span>'


def bullets(items) -> str:
    return "<ul>" + "".join(f"<li>{i}</li>" for i in items) + "</ul>" if items else ""


def kpis(items) -> str:
    cards = "".join(
        f'<div class="card"><div class="kpi">{v}<small>{esc(label)}</small></div>'
        f'<p class="small">{note}</p></div>'
        for v, label, note in items)
    return f'<div class="grid g3">{cards}</div>'


def callout(kind: str, title: str, body: str) -> str:
    cls = {"info": "callout", "warn": "callout warn", "flag": "callout flag"}[kind]
    return f'<div class="{cls}"><p><strong>{title}</strong> {body}</p></div>'


def page(name: str, title: str, lead: str, body: list) -> None:
    links = "".join(f'<a class="chip" href="{href}">{esc(label)}</a>'
                    for href, label in PAGES if href != name)
    inner = (f'<p class="small">NFL Signals Lab · generated by <code>scripts/build_signals.py</code> '
             f'from committed JSON · model version {esc(LE_MODEL_VERSION)}</p>\n'
             f'<h1>{esc(title.split(" — ")[0])}</h1>\n'
             f'<p class="lede">{lead}</p>\n'
             f'<div class="toolbar">{links}</div>\n'
             + "\n".join(body)
             + f'\n<div class="callout"><p><strong>Framework, not just numbers.</strong> The research '
               f'questions, gate design and reward proposal this build implements are written up in the '
               f'<a href="{STRATEGY_PAGE}">NFL Lines &amp; Strategy Lab</a>. Requirement statuses live on '
               f'the <a href="nfl-signals-requirements.html">requirement ledger</a>, and every decision '
               f'taken about a suggestion is on the '
               f'<a href="nfl-signals-suggestions.html">review board</a>.</p>'
               f'<p><strong>Written record.</strong> '
               f'<a href="research/NFL-SIGNALS-EXEC-SUMMARY.md">Executive summary</a> covers the outcome and '
               f'what would change it; <a href="research/NFL-SIGNALS-REVIEW.md">method review</a> covers what a '
               f'reader must not conclude from these numbers, and the decisions that need an owner rather than '
               f'another commit.</p></div>')
    html = head(title, ACTIVE) + inner + foot()
    with open(os.path.join(ROOT, name), "w", encoding="utf-8") as fh:
        fh.write(html)
    print("wrote", name)


