# ------------------------------------------------------------------------- hub
def build_hub(sig, ledger, reqs):
    meta = sig.get("meta", {})
    inputs = meta.get("inputs", {})
    board = sig.get("leaderboard", {})
    entries = board.get("entries", [])
    luck = sig.get("luck", {})
    gates = sig.get("gates", {})
    lm = (ledger or {}).get("meta", {})

    entries = sorted(entries, key=lambda e: (e.get("rank") if e.get("rank") is not None else 99))
    rows = [[num(e.get("rank"), 0), esc(e.get("strategy", "")), esc(e.get("betType", "")),
             num(e.get("n"), 0), num(e.get("logLoss")), num(e.get("brier")), num(e.get("ece")),
             pct(e.get("hitRate")), pct(e.get("hitRateStrong")), num(e.get("improvementVsBaseline")),
             st("qualified" if e.get("qualified") else "not-qualified")] for e in entries]
    board_table = table(
        ["#", "Strategy", "Bet type", "Games scored", "Log loss", "Brier", "Calibration error",
         "Hit rate", "Hit rate on strong picks", "Δ log loss vs home-field baseline", "Meets the gate"],
        rows)

    verdict = ("No strategy has been promoted. On the out-of-sample games available, the best candidate "
               "improves on the naive baselines by less than its own uncertainty, so the ranking is "
               "reported as provisional and the reward rule stays unexercised.")
    if entries:
        top = entries[0]
        naive = ("S1-homefield", "S2-netpoints")
        own = luck.get(top.get("strategy")) or {}
        second = entries[1] if len(entries) > 1 else {}
        lead_by = (second.get("logLoss") - top.get("logLoss")) if second.get("logLoss") is not None else None
        who = ("and that is the finding rather than a formality: the leader is one of the two naive baselines, "
               "so neither the opponent-adjusted ratings nor the availability adjustment beat it on this sample"
               if top.get("strategy") in naive else
               "which is the first time a model has led the baselines here")
        verdict = (f"Out of sample the best record belongs to <strong>{esc(top.get('strategy'))}</strong> at log "
                   f"loss {num(top.get('logLoss'))}, {num(lead_by)} nats ahead of the next strategy ({who}). "
                   f"Its paired difference against the baseline has t = {num(own.get('tStat'), 2)} with a 95% "
                   f"bootstrap interval of {esc(json.dumps(own.get('bootCI95')))}, so it does not clear two "
                   f"standard errors; at this effect size it would need about {num(own.get('nForTwoSigma'), 0)} "
                   f"paired games to be separable from luck and it has {num(top.get('n'), 0)}. The ranking is "
                   f"published as provisional and no strategy is promoted.")
        if any(e.get("qualified") is False for e in entries):
            verdict += (" The two combination strategies (S5, S6) carry no rank at all: they cannot be scored on "
                        "game outcomes alone, and saying so is better than leaving an empty cell.")

    score_rows = kpis([
        (num(inputs.get("gamesWithOfficialScores"), 0), "games with an official score",
         "the backtest sample; 5 played games never got a published label and stay excluded"),
        (num(inputs.get("availabilityRows"), 0), "availability rows today",
         f"across {num(inputs.get('clubsWithAnAvailabilityFile'), 0)} clubs, read from the per-club injury tables"),
        (num(lm.get("rows"), 0), "frozen forward predictions",
         f"{num(lm.get('settled'), 0)} settled · {num(lm.get('open'), 0)} waiting on a result"),
    ])

    body = [
        callout("warn", "No market prices exist in this repository.",
                "Every line published here is a <em>model</em> line. With no timestamped book odds in the repo, "
                "no edge, ROI, closing-line-value or beaten-spread claim is made on any page; what is measured "
                "is forecast accuracy, calibration, and the dependence between related outcomes."),
        "<h2>Verdict</h2>",
        f"<p>{verdict}</p>",
        "<h2>What this run is built from</h2>",
        score_rows,
        f'<p class="small">Leaderboard rule as implemented: {esc(board.get("prizeRule") or board.get("rewards", ""))}</p>',
        "<h2>Out-of-sample leaderboard</h2>",
        f'<p class="small">Ranked on log loss over games predicted from earlier games only '
        f"(weeks {esc(', '.join(str(w) for w in (entries[0].get('weeksCovered') or []))) if entries else '—'}). "
        "Lower is better. A row qualifies only if it beat the naive baselines and cleared the sample gate — "
        "both baselines are scored in the same table so the comparison is visible, not asserted.</p>",
        board_table,
        "<h2>Validation gates</h2>",
        '<p class="small">Gates are the pre-registered rules a strategy must satisfy before it is trusted. They '
        "are filled from this run rather than declared, which is why some of them fail below.</p>",
    ]
    gate_codes = list(next(iter(gates.values())).keys()) if gates else []
    grid = [[esc(strat)] + [st(gates[strat][c].get("status")) for c in gate_codes] for strat in gates]
    body.append(table(["Strategy"] + [esc(c) for c in gate_codes], grid))
    fails = []
    for strat, gg in gates.items():
        for code, g in gg.items():
            if g.get("status") in ("fail", "insufficient-sample", "not-started", "manual-review"):
                fails.append([esc(strat), esc(code), esc(g.get("title", "")), st(g.get("status")),
                              esc(g.get("evidence", ""))])
    if fails:
        body.append("<h3>What is not satisfied, and why</h3>")
        body.append(table(["Strategy", "Gate", "Name", "Status", "Evidence from this run"], fails))
    body += [
        "<h2>Where this goes next</h2>",
        bullets([
            "The forward ledger settles itself once this runs after each game week; six settled slates is what "
            "turns the table above from provisional into evidence.",
            "A dated availability archive is the single highest-value missing input: today the injury data is one "
            "snapshot, so the availability strategy fails its own leakage gate deliberately, and can only be "
            "judged prospectively.",
            "Player-prop combinations stay uncomputed until player-level statistics and prop prices exist; the "
            "method is written into the engine so it runs the day the data arrives.",
            "No official depth-chart page exists, so replacement quality is reported as a gap instead of being "
            "estimated from contract years or snap counts.",
        ]),
        '<p class="small">Reproduce: <code>gh workflow run nfl-lab.yml</code> for the capture (the sandbox has no '
        'outbound HTTP), then <code>python3 scripts/signal_lab.py</code> and '
        '<code>python3 scripts/build_signals.py</code> offline from the committed JSON. '
        'Machine-readable output: <code>data/nfl-signals/signals.json</code>.</p>',
    ]
    page("nfl-signals.html", "NFL Signals Lab — verdict, leaderboard and gates",
         "Independent NFL game forecasts built only from official nfl.com captures, scored out of sample, "
         "with the uncertainty of every claim printed beside the claim.", body)


